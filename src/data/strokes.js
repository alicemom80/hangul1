/** 자음의 획 목록 (없는 글자면 오류) */
export function strokesOf(letter) {
  const strokes = STROKES[letter];
  if (!strokes) throw new Error(`[strokes] 획이 없는 글자입니다: ${letter}`);
  return strokes;
}
